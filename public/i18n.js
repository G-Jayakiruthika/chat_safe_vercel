window.CHATSAFE_TRANSLATE = function translateChatSafe(langCode, key, vars = {}, fallbackText = '') {
  const dict = window.CHATSAFE_I18N || {};
  const base = dict.en || {};
  const local = (langCode && dict[langCode]) || null;
  const rawLocal = local && typeof local[key] === 'string' ? local[key].trim() : '';
  const rawBase = typeof base[key] === 'string' ? base[key].trim() : '';
  const template = rawLocal || rawBase || String(fallbackText || '').trim() || String(key || '');
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : ''));
};
