const GEMINI_MODEL = 'gemini-3.8-flash';
const GEMINI_GENERATE_URL = `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent`;
const REQUEST_TIMEOUT_MS = 9_000;
const MAX_PROMPT_CHARS = 1500;
const CANONICAL_AGENTS = new Set(['vani', 'gemini', 'kavach', 'urimai', 'netra', 'setu']);

const SYSTEM_INSTRUCTION = [
  'Route Indian citizen input as "SCAM" (0-25 safe, 26-65 warn, 66-100 scam) or "CIVIC" (80-99 municipal issue).',
  'Reply ONLY with compact JSON: {"intent":"SCAM|CIVIC","confidence_score":number,"active_agents":["vani","gemini","kavach|urimai","netra","setu"],"summary":"1 sentence","action_draft":"brief 2-line 1930 or petition draft","checklist":["step 1","step 2"]}.',
].join(' ');

/**
 * Normalizes agent names returned by Gemini into canonical agent bus identifiers.
 *
 * @param {unknown} rawAgents Candidate agent array from model output.
 * @param {'SCAM'|'CIVIC'} intent Normalized intent classification.
 * @param {number} confidenceScore Normalized 0-100 confidence/risk score.
 * @returns {string[]} Deduplicated canonical bus agent identifiers.
 */
function normalizeAgents(rawAgents, intent, confidenceScore) {
  const mapToken = (val) => {
    const token = String(val || '').toLowerCase().trim();
    if (!token) return null;
    if (CANONICAL_AGENTS.has(token)) return token;
    for (const id of CANONICAL_AGENTS) {
      if (token.includes(id)) return id;
    }
    return null;
  };

  const mapped = Array.isArray(rawAgents)
    ? [...new Set(rawAgents.map(mapToken).filter(Boolean))]
    : [];

  if (intent === 'CIVIC') {
    const allowed = new Set(['vani', 'gemini', 'urimai', 'setu']);
    if (mapped.includes('netra')) allowed.add('netra');
    return [...allowed];
  }

  const allowed = new Set(['vani', 'gemini', 'kavach']);
  if (confidenceScore > 25 || mapped.includes('netra')) allowed.add('netra');
  if (confidenceScore >= 66 && mapped.includes('setu')) allowed.add('setu');
  return [...allowed];
}

/**
 * Attempts to parse a JSON string into a non-array plain object.
 *
 * @param {string} candidate JSON text candidate.
 * @returns {Record<string, unknown>|null} Parsed plain object or null if invalid.
 */
function tryParseJsonObject(candidate) {
  try {
    const parsed = JSON.parse(candidate);
    if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
      return parsed;
    }
  } catch { /* fall through */ }
  return null;
}

/**
 * Recovers structured fields from a partial JSON fragment truncated near `maxOutputTokens`.
 *
 * @param {string} jsonFragment Slice starting at the opening `{` brace.
 * @returns {Record<string, unknown>|null} Partial verdict object, or null when no JSON fields match.
 */
function recoverPartialJson(jsonFragment) {
  const readJsonString = (key) => {
    const m = jsonFragment.match(new RegExp(`"${key}"\\s*:\\s*"((?:\\\\.|[^"\\\\])*)"`, 'i'));
    if (!m) return '';
    try {
      return JSON.parse(`"${m[1]}"`);
    } catch {
      return m[1].replace(/\\n/g, '\n').replace(/\\"/g, '"');
    }
  };
  const readJsonArray = (key) => {
    const m = jsonFragment.match(new RegExp(`"${key}"\\s*:\\s*\\[([^\\]]*)`, 'i'));
    if (!m) return [];
    const items = [];
    for (const itemMatch of m[1].matchAll(/"((?:\\.|[^"\\])*)"/g)) {
      try {
        items.push(JSON.parse(`"${itemMatch[1]}"`));
      } catch {
        items.push(itemMatch[1]);
      }
    }
    return items;
  };

  const recoveredIntent = readJsonString('intent').toUpperCase();
  const scoreMatch = jsonFragment.match(/"confidence_score"\s*:\s*(\d+(?:\.\d+)?)/i);
  const recoveredSummary = readJsonString('summary');
  if (recoveredIntent !== 'SCAM' && recoveredIntent !== 'CIVIC' && !scoreMatch && !recoveredSummary) {
    return null;
  }

  return {
    intent: recoveredIntent === 'CIVIC' ? 'CIVIC' : 'SCAM',
    confidence_score: scoreMatch ? Number(scoreMatch[1]) : (recoveredIntent === 'CIVIC' ? 90 : 50),
    active_agents: readJsonArray('active_agents'),
    summary: recoveredSummary,
    action_draft: readJsonString('action_draft'),
    checklist: readJsonArray('checklist'),
  };
}

/**
 * Parses model text output into a structured object, handling fenced JSON, truncated JSON, and plain text.
 *
 * @param {string} rawText Raw text generated by the Gemini model.
 * @returns {Record<string, unknown>} Parsed JSON object or structured plain-text wrapper.
 */
function parseGeneratedOutput(rawText) {
  const trimmed = String(rawText || '').trim();
  const direct = tryParseJsonObject(trimmed);
  if (direct) return direct;

  const unfenced = trimmed.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/i, '').trim();
  const parsedFence = tryParseJsonObject(unfenced);
  if (parsedFence) return parsedFence;

  const firstBrace = unfenced.indexOf('{');
  const lastBrace = unfenced.lastIndexOf('}');
  if (firstBrace !== -1 && lastBrace > firstBrace) {
    const sliced = tryParseJsonObject(unfenced.slice(firstBrace, lastBrace + 1));
    if (sliced) return sliced;
  }
  if (firstBrace !== -1) {
    const recovered = recoverPartialJson(unfenced.slice(firstBrace));
    if (recovered) return recovered;
  }

  const isCivicText = /\b(civic|water\s*pipe|pothole|broken\s*road|street\s*light|panchayat|municipality|petition)\b/i.test(trimmed);
  return {
    intent: isCivicText ? 'CIVIC' : 'SCAM',
    confidence_score: 50,
    active_agents: [],
    summary: trimmed,
    action_draft: '',
    checklist: [],
  };
}

/**
 * Normalizes and validates parsed Gemini JSON into the guaranteed proxy response shape.
 *
 * @param {Record<string, unknown>} parsed Raw parsed JSON object from the Gemini API.
 * @param {string} cleanPrompt Sanitized user prompt fallback.
 * @param {string} [rawText=''] Raw generated text from the Gemini candidate response.
 * @param {string} [modelName=''] Upstream Gemini model identifier that succeeded.
 * @returns {{intent: 'SCAM'|'CIVIC', confidence_score: number, active_agents: string[], summary: string, action_draft: string, checklist: string[], text: string, model?: string}}
 */
function normalizeProxyPayload(parsed, cleanPrompt, rawText = '', modelName = '') {
  const rawIntent = String(parsed?.intent || '').toUpperCase().trim();
  const intent = rawIntent === 'CIVIC' ? 'CIVIC' : 'SCAM';
  const rawScore = Number(parsed?.confidence_score);
  const confidenceScore = Number.isFinite(rawScore)
    ? Math.max(0, Math.min(100, Math.round(rawScore)))
    : (intent === 'CIVIC' ? 92 : 50);

  const summary = String(parsed?.summary || '').trim()
    || (intent === 'CIVIC'
      ? `Civic grievance classified for Urimai action: ${cleanPrompt.slice(0, 120)}`
      : confidenceScore <= 25
        ? 'Looks safe. No common cyber scam pattern detected.'
        : 'Suspicious cyber fraud pattern detected. Verify before acting.');

  const actionDraft = String(parsed?.action_draft || '').trim();
  const rawChecklist = Array.isArray(parsed?.checklist)
    ? parsed.checklist.map((item) => String(item || '').trim()).filter(Boolean).slice(0, 6)
    : [];
  const checklist = rawChecklist.length
    ? rawChecklist
    : intent === 'CIVIC'
      ? [
        'Verify detected municipal ward / GPS coordinates.',
        'Export the bilingual Urimai PDF or submit via State CM Helpline.',
      ]
      : confidenceScore <= 25
        ? ['Continue practicing safe digital hygiene and never share OTPs.']
        : ['Do not transfer money or share OTP/PIN.', 'Report immediately at 1930 or cybercrime.gov.in.'];

  const text = String(rawText || '').trim() || summary;
  const model = String(modelName || '').replace(/^models\//i, '');

  return {
    intent,
    confidence_score: confidenceScore,
    active_agents: normalizeAgents(parsed?.active_agents, intent, confidenceScore),
    summary,
    action_draft: actionDraft,
    checklist,
    text,
    ...(model ? { model } : {}),
  };
}

/**
 * Sanitizes text for safe logging and error payloads without exposing credentials.
 *
 * @param {unknown} raw Raw error text or response snippet.
 * @param {string} secretKey Secret credential string to redact.
 * @returns {string} Sanitized snippet capped at 600 chars.
 */
function sanitizeText(raw, secretKey) {
  let out = String(raw || '');
  if (secretKey) {
    out = out.replaceAll(secretKey, '[REDACTED]');
    out = out.replaceAll(encodeURIComponent(secretKey), '[REDACTED]');
  }
  out = out.replace(/([?&]key=)[^&\s"']+/gi, '$1[REDACTED]');
  return out.trim().slice(0, 600);
}

/**
 * Safely extracts and sanitizes an upstream response body snippet without exposing credentials.
 *
 * @param {Response|any} res Upstream fetch response object.
 * @param {string} secretKey Secret credential string to redact if echoed.
 * @returns {Promise<string>} Sanitized error/body snippet.
 */
async function readSafeBody(res, secretKey) {
  let raw = '';
  try {
    if (typeof res?.text === 'function') {
      raw = await res.text();
    } else if (typeof res?.json === 'function') {
      const parsed = await res.json();
      raw = JSON.stringify(parsed);
    }
  } catch {
    raw = '';
  }
  return sanitizeText(raw, secretKey);
}

/**
 * Parses and validates the incoming proxy JSON request body.
 *
 * @param {unknown} rawBody Raw `req.body` value (Buffer, JSON string, or object).
 * @returns {{ok: true, cleanPrompt: string, cleanLang: string, cleanMode: string} | {ok: false, status: number, error: string}}
 */
function parseRequestBody(rawBody) {
  let body = Buffer.isBuffer(rawBody) ? rawBody.toString('utf8') : rawBody;
  if (typeof body === 'string') {
    try {
      body = JSON.parse(body);
    } catch {
      return { ok: false, status: 400, error: 'Invalid JSON request body.' };
    }
  }
  if (!body || typeof body !== 'object' || Array.isArray(body)) {
    return { ok: false, status: 400, error: 'A valid JSON request object is required.' };
  }

  const { prompt, language = 'en', mode = 'auto' } = body;
  if (typeof prompt !== 'string' || !prompt.trim()) {
    return { ok: false, status: 400, error: 'A non-empty prompt is required.' };
  }

  return {
    ok: true,
    cleanPrompt: prompt.trim().slice(0, MAX_PROMPT_CHARS),
    cleanLang: String(language || 'en').trim().slice(0, 32) || 'en',
    cleanMode: String(mode || 'auto').trim().slice(0, 32) || 'auto',
  };
}

/**
 * Builds the serialized JSON payload for Gemini `:generateContent`.
 *
 * @param {string} cleanPrompt Sanitized user prompt text.
 * @param {string} cleanLang Preferred language code.
 * @param {string} cleanMode Interaction mode token.
 * @param {boolean} withThinkingConfig Whether to include `thinkingConfig: { thinkingBudget: 0 }`.
 * @returns {string} JSON-encoded Gemini API request body.
 */
function buildGenerateRequestBody(cleanPrompt, cleanLang, cleanMode, withThinkingConfig) {
  return JSON.stringify({
    systemInstruction: {
      parts: [{ text: `${SYSTEM_INSTRUCTION} Lang: ${cleanLang}. Mode: ${cleanMode}.` }],
    },
    contents: [{
      role: 'user',
      parts: [{ text: cleanPrompt }],
    }],
    generationConfig: {
      ...(withThinkingConfig ? { thinkingConfig: { thinkingBudget: 0 } } : {}),
      maxOutputTokens: 600,
      temperature: 0.3,
    },
  });
}

/**
 * Extracts concatenated text from the primary Gemini candidate payload.
 *
 * @param {any} upstreamJson Parsed JSON response from Gemini `:generateContent`.
 * @returns {string} Concatenated candidate text, or empty string if absent.
 */
function extractCandidateText(upstreamJson) {
  return upstreamJson?.candidates?.[0]?.content?.parts
    ?.map((part) => (typeof part?.text === 'string' ? part.text : ''))
    .join('') || '';
}

/**
 * Logs a sanitized upstream failure and sends a uniform HTTP 503 fallback payload.
 *
 * @param {any} res HTTP response object.
 * @param {number} status Upstream HTTP status code.
 * @param {string} upstreamBody Sanitized upstream error snippet.
 * @returns {any} HTTP response return value.
 */
function sendUpstreamFailure(res, status, upstreamBody) {
  console.error('Gemini upstream failure:', status, upstreamBody);
  return res.status(503).json({
    error: 'Live AI proxy error',
    fallback: true,
    upstreamStatus: status,
    upstreamBody: upstreamBody.slice(0, 400),
  });
}

/**
 * Creates a Vercel-compatible serverless request handler with injectable dependencies for testing.
 *
 * @param {{fetchImpl?: typeof fetch, env?: Record<string, string|undefined>, timeoutMs?: number}} [deps] Optional dependency overrides.
 * @returns {(req: any, res: any) => Promise<void>} Serverless HTTP handler.
 */
export function createGeminiHandler(deps = {}) {
  const fetchFn = deps.fetchImpl || globalThis.fetch;
  const timeoutMs = Number.isFinite(deps.timeoutMs) ? deps.timeoutMs : REQUEST_TIMEOUT_MS;

  return async function geminiHandler(req, res) {
    res.setHeader('Cache-Control', 'no-store');
    res.setHeader('Content-Type', 'application/json; charset=utf-8');

    if (String(req?.method || '').toUpperCase() !== 'POST') {
      res.setHeader('Allow', 'POST');
      return res.status(405).json({ error: 'Method not allowed. Use POST.' });
    }

    const rawKey = deps.env ? deps.env.GEMINI_API_KEY : process.env.GEMINI_API_KEY;
    const apiKey = (typeof rawKey === 'string' ? rawKey : String(rawKey || '')).trim();
    if (!apiKey) {
      return res.status(503).json({
        error: 'Missing GEMINI_API_KEY',
        fallback: true,
        stage: 'missing_key',
      });
    }

    const parsedReq = parseRequestBody(req?.body);
    if (!parsedReq.ok) {
      return res.status(parsedReq.status).json({ error: parsedReq.error });
    }
    const { cleanPrompt, cleanLang, cleanMode } = parsedReq;

    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);
    const url = `${GEMINI_GENERATE_URL}?key=${encodeURIComponent(apiKey)}`;
    const sendGenerate = (withThinkingConfig) => fetchFn(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      signal: controller.signal,
      body: buildGenerateRequestBody(cleanPrompt, cleanLang, cleanMode, withThinkingConfig),
    });

    try {
      let response = await sendGenerate(true);
      if (!response?.ok) {
        let status = Number.isInteger(response?.status) ? response.status : 503;
        let upstreamBody = await readSafeBody(response, apiKey);

        if (status === 400 && /thinkingBudget|thinkingConfig|thinking_budget|thinking_config/i.test(upstreamBody)) {
          response = await sendGenerate(false);
          if (!response?.ok) {
            status = Number.isInteger(response?.status) ? response.status : 503;
            upstreamBody = await readSafeBody(response, apiKey);
          }
        }

        if (!response?.ok) {
          return sendUpstreamFailure(res, status, upstreamBody);
        }
      }

      const upstreamJson = await response.json();
      const rawText = extractCandidateText(upstreamJson);
      if (!rawText.trim()) {
        const status = Number.isInteger(response?.status) ? response.status : 502;
        return sendUpstreamFailure(res, status, 'Empty or malformed upstream response.');
      }

      const parsed = parseGeneratedOutput(rawText);
      return res.status(200).json(normalizeProxyPayload(parsed, cleanPrompt, rawText, GEMINI_MODEL));
    } catch (err) {
      if (controller.signal.aborted || err?.name === 'AbortError') {
        console.error('Gemini request timed out');
        console.error('Gemini upstream failure:', 504, 'Upstream Gemini request timed out');
        return res.status(503).json({
          error: 'Upstream Gemini request timed out',
          fallback: true,
          upstreamStatus: 504,
          upstreamBody: 'Upstream Gemini request timed out',
        });
      }
      const errorText = sanitizeText(err?.message || 'Upstream request failed.', apiKey);
      return sendUpstreamFailure(res, 503, errorText);
    } finally {
      clearTimeout(timer);
    }
  };
}

const defaultHandler = createGeminiHandler();

/**
 * Vercel Serverless Function entrypoint (`POST /api/gemini`).
 *
 * @param {import('http').IncomingMessage & {body?: unknown, method?: string}} req Incoming HTTP request.
 * @param {import('http').ServerResponse & {status: (code: number) => any, json: (payload: unknown) => any}} res HTTP response object.
 * @returns {Promise<void>} Resolves once JSON response is sent.
 */
export default async function handler(req, res) {
  return defaultHandler(req, res);
}
